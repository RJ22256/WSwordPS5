import sys,io; sys.path.insert(0,'lyt')
from ds import build
from PIL import Image
def fnv(b):
    h=0xcbf29ce484222325
    for x in b: h=((h^x)*0x100000001b3)&0xFFFFFFFFFFFFFFFF
    return h
orig=open('lytdata/tipsNN.bflyt','rb').read()
L=build('lytdata/tipsNN.bflyt','lytdata/tipsNN_ds.bflyt')
f=Image.open('lytdata/ds_front.png'); t=Image.open('lytdata/ds_top.png')
def png(im):
    b=io.BytesIO(); im.save(b,'PNG',optimize=True); return b.getvalue()
fp,tp=png(f),png(t)
h0=fnv(open('lytdata/NN00.rg','rb').read()); h1=fnv(open('lytdata/NN01.rg','rb').read())
out=[]
out.append('// generated by tools/pad_illust/gen_c.py: do not edit (the drawings: tools/pad_illust/draw_pad.py)')
out.append('#include <stdint.h>\n#include <stddef.h>\n#include "pad_illust.h"\n')
out.append(f'const uint64_t k_pad_layout_hash = 0x{fnv(orig):016x}ull;  // blyt/PaAllControllerTipsNN_00.bflyt, 1.8.2')
out.append(f'const size_t k_pad_layout_size = {len(orig)};')
out.append(f'const uint64_t k_pad_tex_hash[2] = {{0x{h0:016x}ull, 0x{h1:016x}ull}};  // Nt_NNillust_00 (576x288), _01 (576x100), RG8')
out.append('const PadPaneEdit k_pad_edits[] = {')
for n,(tx,ty,rz,sx,sy,w,h) in L.edits.items():
    out.append(f'    {{"{n}", {tx:.3f}f, {ty:.3f}f, {rz:.1f}f, {sx:.3f}f, {sy:.3f}f, {w:.3f}f}},')
out.append('};')
out.append('const size_t k_pad_nedits = sizeof k_pad_edits / sizeof *k_pad_edits;')
for nm,b in (('front',fp),('top',tp)):
    out.append(f'const size_t k_pad_{nm}_png_size = {len(b)};')
    out.append(f'const uint8_t k_pad_{nm}_png[] = {{')
    for i in range(0,len(b),24): out.append('    '+', '.join(f'0x{x:02x}' for x in b[i:i+24])+',')
    out.append('};')
open(sys.argv[1],'w').write('\n'.join(out)+'\n')
print(len(L.edits),'edits; png',len(fp),len(tp))
