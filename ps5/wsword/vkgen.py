#!/usr/bin/env python3
"""ps5/wsword/vkgen.py <vulkan_core.h> <out.c> - the Vulkan commands for the WSword runtime on the console.

The runtime calls Vulkan's commands by name, as it does against the PC's loader; the console has no loader, only the
RADV linked into the title, which exports nothing but vk_icdGetInstanceProcAddr. This writes a definition of every
command in vulkan_core.h that resolves the driver's own entry point on its first call:
  global commands      vk_icdGetInstanceProcAddr(NULL, name)
  instance commands    vk_icdGetInstanceProcAddr(instance, name), the instance vkCreateInstance made
  device commands      vkGetDeviceProcAddr(device, name) once vkCreateDevice made one (the driver's entry points, no
                       trampoline), through the instance before that
A command the driver doesn't have stops the runtime with its name in the log rather than jumping to null.
"""
import re
import sys

GLOBAL = {"vkCreateInstance", "vkEnumerateInstanceExtensionProperties", "vkEnumerateInstanceLayerProperties",
          "vkEnumerateInstanceVersion"}
DEVICE_FIRST = ("VkDevice", "VkQueue", "VkCommandBuffer")


def main():
    src, out = sys.argv[1], sys.argv[2]
    text = open(src).read()
    # VKAPI_ATTR <ret> VKAPI_CALL vkName(<params>);
    protos = re.findall(r"VKAPI_ATTR\s+(.+?)\s+VKAPI_CALL\s+(vk\w+)\s*\(([^;]*?)\);", text, re.S)
    seen = set()
    lines = ["// generated by ps5/wsword/vkgen.py from vulkan_core.h: do not edit",
             "#include <stdio.h>", "#include <stdlib.h>", "#include <vulkan/vulkan.h>", "",
             "VKAPI_ATTR PFN_vkVoidFunction VKAPI_CALL vk_icdGetInstanceProcAddr(VkInstance instance, const char *name);",
             "static VkInstance g_instance;", "static VkDevice g_device;",
             "static PFN_vkGetDeviceProcAddr g_device_proc;", "",
             "static PFN_vkVoidFunction resolve(const char *name, int kind) {  // 0 global, 1 instance, 2 device",
             "    PFN_vkVoidFunction f = NULL;",
             "    if (kind == 2 && g_device && g_device_proc) f = g_device_proc(g_device, name);",
             "    if (!f) f = vk_icdGetInstanceProcAddr(kind ? g_instance : NULL, name);",
             "    if (!f) {",
             "        fprintf(stderr, \"FATAL: the console's Vulkan driver has no %s\\n\", name);",
             "        fflush(stderr);",
             "        abort();",
             "    }",
             "    return f;",
             "}", ""]
    device_ptrs = []
    for ret, name, params in protos:
        if name in seen or name == "vkGetInstanceProcAddr":
            continue
        seen.add(name)
        params = " ".join(params.split())
        if params in ("void", ""):
            plist, args = "void", ""
        else:
            names = []
            for p in params.split(","):
                p = p.strip()
                m = re.search(r"(\w+)\s*(\[[^\]]*\])?\s*$", p)
                names.append(m.group(1))
            plist, args = params, ", ".join(names)
        first = params.split(",")[0].strip().split()[0] if plist != "void" else ""
        if name in GLOBAL:
            kind = 0
        elif first in DEVICE_FIRST and name != "vkGetDeviceProcAddr":
            kind = 2
        else:
            kind = 1
        ptr = f"p_{name}"
        if kind == 2:
            device_ptrs.append(ptr)
        lines.append(f"static PFN_{name} {ptr};")
        body = [f"    if (!{ptr}) {ptr} = (PFN_{name})resolve(\"{name}\", {kind});"]
        call = f"{ptr}({args})"
        if name == "vkCreateInstance":
            body.append(f"    VkResult r = {call};")
            body.append("    if (r == VK_SUCCESS) g_instance = *pInstance;")
            body.append("    return r;")
        elif name == "vkCreateDevice":
            body.append(f"    VkResult r = {call};")
            body.append("    if (r == VK_SUCCESS && !g_device) {  // the driver's own entry points from here on")
            body.append("        g_device_proc = (PFN_vkGetDeviceProcAddr)vk_icdGetInstanceProcAddr(g_instance, \"vkGetDeviceProcAddr\");")
            body.append("        g_device = *pDevice;")
            body.append("        wsvk_device_reset();")
            body.append("    }")
            body.append("    return r;")
        elif name == "vkDestroyDevice":
            body.append(f"    {call};")
            body.append("    if (device == g_device) { g_device = NULL; wsvk_device_reset(); }")
        elif ret == "void":
            body.append(f"    {call};")
        else:
            body.append(f"    return {call};")
        if name == "vkCreateDevice":
            lines.append("static void wsvk_device_reset(void);")
        if name == "vkDestroyDevice" and "static void wsvk_device_reset(void);" not in lines:
            lines.append("static void wsvk_device_reset(void);")
        lines.append(f"VKAPI_ATTR {ret} VKAPI_CALL {name}({plist}) {{")
        lines.extend(body)
        lines.append("}")
    lines.append("")
    lines.append("VKAPI_ATTR PFN_vkVoidFunction VKAPI_CALL vkGetInstanceProcAddr(VkInstance instance, const char *pName) {")
    lines.append("    return vk_icdGetInstanceProcAddr(instance, pName);")
    lines.append("}")
    lines.append("")
    lines.append("static void wsvk_device_reset(void) {  // (device commands resolved again for the device made)")
    for p in device_ptrs:
        lines.append(f"    {p} = NULL;")
    lines.append("}")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"vkgen: {len(seen) + 1} commands ({len(device_ptrs)} device-level)")


main()
