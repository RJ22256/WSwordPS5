#!/usr/bin/env python3
"""ps5/wsword/configure.py - writes build/wsword/build.ninja: the WSword runtime (wsword/, the PC's sources) compiled
for the console with the payload SDK's prospero-clang into one static archive, libwsword.a, that the title links.

    ps5/wsword/configure.py --sdk <payload SDK> --deps <prefix> [--out build/wsword]

--deps: the console builds of what the runtime uses (ps5/wsword/deps.sh): include/ with SDL3 (the subset the title
implements: ps5/wsword/sdl), vulkan, shaderc, libav*, zlib.

The flags follow the PC Makefile's (wsword/Makefile.pc): the runtime at -O2 with the console's CPU (Zen 2) as the
target, frame pointers kept for the crash log's backtrace (runtime/platform/ps5.c), and the ids the PC computes the same
way (the game code's id names the PS5 target's flags: the PC export builds the game code with them).
"""
import argparse
import hashlib
import os
import shlex
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
W = os.path.join(ROOT, "wsword")

# The game code's flags for the console: the PC Makefile's GENFLAGS_PS5 / GENFLAGS_ZIG_PS5 (wsword/Makefile.pc), which
# WSword Configuration's PS5 export builds it with - read from there, so the two ids agree (runtime/gamelib.c).
def makefile_var(name):
    for line in open(os.path.join(W, "Makefile.pc")):
        if line.startswith(name + " :="):
            return line.split(":=", 1)[1].split("#")[0].strip()
    raise SystemExit(f"wsword/Makefile.pc has no {name} (a WSword without the PS5 export)")


GENFLAGS = " ".join(makefile_var("GENFLAGS_PS5").split())
GENFLAGS_ZIG = makefile_var("GENFLAGS_ZIG_PS5")
ARCH = next(f for f in GENFLAGS.split() if f.startswith("-march="))  # (the console's CPU: AMD Zen 2)


def sha16(paths, extra=""):
    h = hashlib.sha256()
    for p in paths:
        with open(os.path.join(W, p), "rb") as f:
            h.update(f.read())
    h.update(extra.encode())
    return h.hexdigest()[:16]


def files(rel, exts):
    d = os.path.join(W, rel)
    return sorted(os.path.join(rel, f) for f in os.listdir(d) if os.path.splitext(f)[1] in exts)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sdk", required=True)
    ap.add_argument("--deps", required=True)
    ap.add_argument("--out", default=os.path.join(ROOT, "build", "wsword"))
    a = ap.parse_args()
    sdk, deps, out = (os.path.abspath(x) for x in (a.sdk, a.deps, a.out))
    os.makedirs(out, exist_ok=True)

    gamelib_srcs = ("tools/gen.py tools/lifter.py tools/analyze.py tools/nso.py tools/passes.py tools/patches.py "
                    "tools/simd_c.py tools/gamelib_entry.c runtime/hle/hle_symbols.txt runtime/cpu.h runtime/simd.h "
                    "runtime/simd_fp.h runtime/simd_softfma.h runtime/gamelib.h tools/layout.py tools/game_sites.py").split()
    gamelib_id = sha16(gamelib_srcs, GENFLAGS + "\n" + GENFLAGS_ZIG + "\n")
    translator_id = sha16(["runtime/nvn/maxwell/translate.c", "runtime/nvn/maxwell/shader.h"])
    spirv_id = sha16(["runtime/nvn/vulkan/spirv.c"])
    with open(os.path.join(W, "SOURCE")) as f:
        source = f.readline().strip().split(" (")[0].replace("SheikahSlate ", "commit ")[:24]
    version = open(os.path.join(W, "VERSION")).read().strip() if os.path.exists(os.path.join(W, "VERSION")) else "?"

    cc = os.path.join(sdk, "bin", "prospero-clang")
    cxx = os.path.join(sdk, "bin", "prospero-clang++")
    ar = os.path.join(sdk, "bin", "prospero-ar")
    # ps5/wsword/compat first: what the SDK's FreeBSD headers make of the PC's (malloc.h, stdatomic.h in C++)
    compat = os.path.join(ROOT, "ps5", "wsword", "compat")
    inc = f"-I{compat} -I{deps}/include"
    common = (f"-O2 -g {ARCH} -fno-omit-frame-pointer -fno-strict-aliasing -Wall -Wno-unused-function -Wno-format "
              f"-Wno-unknown-warning-option -Wno-unreachable-code-generic-assoc -DWSWORD_PS5=1 -DWSWORD_EDITION='\"PS5\"' "
              # (every thread the runtime starts begins on the host CPUs: runtime/platform/ps5.c wsword_pthread_create)
              f"-Dpthread_create=wsword_pthread_create")
    rtflags = f"{common} -std=gnu17 -Iruntime -Iruntime/nvn -isystem third_party -isystem third_party/stb {inc}"
    imgui = "third_party/imgui"
    cxxflags = (f"{common} -std=c++17 -I{imgui} -I{imgui}/backends -Iruntime -Iruntime/nvn -isystem third_party "
                f"-Ithird_party/stb {inc}")
    ffx = "third_party/FidelityFX"
    ffx_inc = (f"-I{ffx}/sdk/include -I{ffx}/sdk/src/components -I{ffx}/sdk/src/shared -I{ffx}/sdk/src/backends/shared")
    lsfg = "third_party/lsfg-vk"
    lsfgflags = (f"{common} -include {compat}/lsfg_prefix.h -std=c++20 -fexceptions -frtti -DVK_NO_PROTOTYPES {inc} -I{lsfg}/lsfg-vk-common/include "
                 f"-I{lsfg}/lsfg-vk-backend/include -I{lsfg}/lsfg-vk-backend/src")

    n = []
    n.append(f"# generated by ps5/wsword/configure.py (WSword {version}, {source}): do not edit\n")
    n.append(f"root = {W}\nbuilddir = {out}\n")
    n.append(f"rule cc\n  command = cd $root && {cc} -MD -MF $out.d $flags -c $in -o $out\n  depfile = $out.d\n  deps = gcc\n  description = cc $in\n")
    n.append(f"rule cxx\n  command = cd $root && {cxx} -MD -MF $out.d $flags -c $in -o $out\n  depfile = $out.d\n  deps = gcc\n  description = c++ $in\n")
    n.append(f"rule ar\n  command = rm -f $out && {ar} rcs $out $in\n  description = ar $out\n")
    # SMAA's reference shader as a C string (the PC Makefile's rule)
    n.append("rule smaa\n  command = LC_ALL=C tr -d '\\r' < $in | LC_ALL=C tr '\\200-\\377' '?' | "
             "sed -e 's/\\\\/\\\\\\\\/g' -e 's/\"/\\\\\"/g' -e 's/^/\"/' -e 's/$$/\\\\n\"/' > $out\n")
    n.append(f"rule configure\n  command = {sys.executable} {os.path.abspath(__file__)} --sdk {sdk} --deps {deps} --out {out}\n  generator = 1\n")
    n.append(f"build {out}/build.ninja: configure {os.path.abspath(__file__)} {W}/SOURCE\n")
    smaa_inc = f"{out}/inc/smaa_hlsl.inc"
    n.append(f"build {smaa_inc}: smaa {W}/third_party/smaa/SMAA.hlsl\n")

    objs = []

    def obj(src, rule, flags, implicit=""):
        o = f"{out}/obj/{os.path.splitext(src)[0]}.o"
        objs.append(o)
        n.append(f"build {o}: {rule} {W}/{src}{(' | ' + implicit) if implicit else ''}\n  flags = {flags}\n")

    rt = [s for s in files("runtime", {".c"})] + files("runtime/hle", {".c"}) + files("runtime/services", {".c"}) + \
        files("runtime/nvn", {".c"}) + files("runtime/nvn/maxwell", {".c"}) + ["runtime/platform/ps5.c"]
    extra = {
        "runtime/nvn/maxwell/translate.c": f"-DTRANSLATOR_ID='\"{translator_id}\"'",
        "runtime/main.c": f"-DSW_SOURCE='\"{source}, PS5\"'",
        "runtime/gamelib.c": (f"-DGAMELIB_ID='\"{gamelib_id}\"' -DGAMELIB_ARCH='\"{ARCH}\"' "
                              f"-DGAMELIB_ARCH_COMPAT='\"{ARCH}\"' -DGAMELIB_ID_COMPAT='\"{gamelib_id}\"'"),
        "runtime/gamebuild.c": (f"-DGAMELIB_CFLAGS='\"{GENFLAGS.replace(' -Iruntime', '')}\"' "
                                f"-DGAMELIB_ZIGFLAGS='\"{GENFLAGS_ZIG}\"' -DGAMELIB_SHARED='\"-shared\"'"),
        "runtime/nvn/smaa_data.c": f"-I{out}/inc -Ithird_party/smaa/Textures",
    }
    for s in rt:
        obj(s, "cc", rtflags + " " + extra.get(s, ""), smaa_inc if s.endswith("smaa_data.c") else "")
    # the console's side (ps5/wsword): the SDL3 subset, the Vulkan commands (vkgen.py), the process end
    ps5w = os.path.join(ROOT, "ps5", "wsword")
    for s in ("sdl/sdl_ps5.c", "ps5_glue.c", "ps5_cwd.c"):
        o = f"{out}/obj/ps5/{os.path.splitext(s)[0]}.o"
        objs.append(o)
        n.append(f"build {o}: cc {ps5w}/{s}\n  flags = {common} -std=gnu17 {inc}\n")
    vkc = f"{out}/gen/vk_dispatch.c"
    n.append(f"rule vkgen\n  command = {sys.executable} {ps5w}/vkgen.py $in $out\n  description = vkgen\n")
    n.append(f"build {vkc}: vkgen {deps}/include/vulkan/vulkan_core.h | {ps5w}/vkgen.py\n")
    objs.append(f"{out}/obj/ps5/vk_dispatch.o")
    n.append(f"build {out}/obj/ps5/vk_dispatch.o: cc {vkc}\n  flags = {common} -std=gnu17 -w {inc}\n")
    for s in files("runtime/nvn/vulkan", {".c"}):
        obj(s, "cc", rtflags + (f" -DSPIRV_ID='\"{spirv_id}\"'" if s.endswith("spirv.c") else ""))
    for s in files("runtime/nvn/vulkan", {".cpp"}):
        f = cxxflags
        if s.endswith("framegen.cpp"):
            f = f"-include {ffx}/ffx_compat.h {ffx_inc} -I{ffx}/spirv {cxxflags}"
        elif s.endswith("fsr3.cpp"):
            f = f"-DSW_FSR3=1 -include {ffx}/ffx_compat.h {ffx_inc} {cxxflags}"
        elif s.endswith("lsfg.cpp"):
            f += f" -I{lsfg}/lsfg-vk-backend/include"
        obj(s, "cxx", f)
    for s in files("runtime/ui", {".mm"}):
        obj(s, "cxx", "-x c++ " + cxxflags)
    for s in ("imgui.cpp", "imgui_draw.cpp", "imgui_tables.cpp", "imgui_widgets.cpp",
              "backends/imgui_impl_sdl3.cpp", "backends/imgui_impl_vulkan.cpp"):
        obj(f"{imgui}/{s}", "cxx", cxxflags)
    ffx_src = [f"{ffx}/sdk/src/components/frameinterpolation/ffx_frameinterpolation.cpp",
               f"{ffx}/sdk/src/components/opticalflow/ffx_opticalflow.cpp",
               f"{ffx}/sdk/src/components/fsr3upscaler/ffx_fsr3upscaler.cpp", f"{ffx}/sdk/src/backends/vk/ffx_vk.cpp"]
    ffx_src += files(f"{ffx}/sdk/src/shared", {".cpp"})
    for s in ffx_src:
        obj(s, "cxx", f"{common} -std=c++17 -w -include {ffx}/ffx_compat.h {ffx_inc} -I{ffx}/sdk/include/FidelityFX/gpu {inc}")
    for d in (f"{lsfg}/lsfg-vk-common/src", f"{lsfg}/lsfg-vk-backend/src"):
        for dp, _, fs in os.walk(os.path.join(W, d)):
            for f in sorted(fs):
                if f.endswith(".cpp"):
                    obj(os.path.relpath(os.path.join(dp, f), W), "cxx", lsfgflags)

    # what the game code may import, by name (exports.py: runtime/elfload.c resolves the library's imports with it)
    ps5w = os.path.join(ROOT, "ps5", "wsword")
    n.append(f"rule exports\n  command = {sys.executable} {ps5w}/exports.py --sdk {sdk} --out $out $in\n  description = exports\n")
    n.append(f"build {out}/gen/exports.c: exports {' '.join(objs)} | {ps5w}/exports.py\n")
    n.append(f"build {out}/obj/ps5/exports.o: cc {out}/gen/exports.c\n  flags = {common} -std=gnu17 -w\n")
    objs.append(f"{out}/obj/ps5/exports.o")
    n.append(f"build {out}/libwsword.a: ar {' '.join(objs)}\n")
    n.append(f"default {out}/libwsword.a\n")
    with open(os.path.join(out, "build.ninja"), "w") as f:
        f.write("\n".join(n))
    with open(os.path.join(out, "ids.txt"), "w") as f:
        f.write(f"version {version}\nsource {source}\ngamelib {gamelib_id}\ngenflags {GENFLAGS}\n"
                f"translator {translator_id}\nspirv {spirv_id}\n")
    print(f"build/wsword: {len(objs)} objects, game code id {gamelib_id}")


main()
