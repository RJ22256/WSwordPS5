#!/usr/bin/env python3
"""ps5/wsword/exports.py --sdk <payload SDK> --out <exports.c> <object>... - what the game code may import on the
console, by name (runtime/gamelib.c: runtime/elfload.c resolves the library's imports from this table; a title has no
dynamic linker that would find them):
  - every C function and variable the runtime's objects define (its rt_* hooks, rt_dispatch, g_fnprof...)
  - the functions the game code's libc headers declare (string.h, strings.h, math.h, fenv.h, setjmp.h: what cpu.h,
    simd.h and the generated code include), those a module a title loads exports
The table is sorted by name; each entry is the symbol's address as the title's own link resolves it.
"""
import argparse
import glob
import os
import re
import subprocess

HEADERS = ["string.h", "strings.h", "math.h", "fenv.h", "setjmp.h"]
# what the compiler itself may call in code that names none of them (copies, clears)
ALWAYS = ["memcpy", "memmove", "memset", "memcmp"]
# stubs of modules a title doesn't load: their names are null at run time (ps5/tools/link-title.sh refuses them)
NOT_LOADED = ("libkernel_sys.so", "libScePosixForWebKit.so")


def nm(tool, args):
    return subprocess.run([tool] + args, capture_output=True, text=True).stdout


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sdk", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("objects", nargs="+")
    a = ap.parse_args()
    tool = os.path.join(a.sdk, "bin", "llvm-nm")
    names = set()
    for line in nm(tool, ["--defined-only", "-g"] + a.objects).splitlines():
        p = line.split()
        if len(p) == 3 and p[1] in "TDBRCVW" and not p[2].startswith(("_Z", "__", ".")):
            names.add(p[2])
    exported = set()
    for so in glob.glob(os.path.join(a.sdk, "target", "lib", "*.so")):
        if os.path.basename(so) in NOT_LOADED:
            continue
        exported.update(l.split()[-1] for l in nm(tool, ["-D", "--defined-only", so]).splitlines() if l.split())
    declared = set(ALWAYS)
    inc = os.path.join(a.sdk, "target", "include")
    for h in HEADERS:
        text = open(os.path.join(inc, h), errors="replace").read()
        text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
        for m in re.finditer(r"\b([A-Za-z_]\w*)\s*\(", text):
            declared.add(m.group(1))
    libc = sorted(n for n in declared & exported if not n.startswith("__") or n in ("__isnan", "__isinf"))
    allnames = sorted(names | set(libc))
    out = ["// generated by ps5/wsword/exports.py: do not edit", "#include <stddef.h>",
           "typedef struct { const char *name; void *addr; } ElfExport;"]
    for i, n in enumerate(allnames):
        out.append(f'extern char x{i}[] __asm__("{n}");')
    out.append("const ElfExport g_wsword_exports[] = {")
    out.extend(f'    {{"{n}", x{i}}},' for i, n in enumerate(allnames))
    out.append("};")
    out.append(f"const size_t g_wsword_nexports = {len(allnames)};")
    with open(a.out, "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"exports: {len(names)} of the runtime's, {len(libc)} of libc's")


main()
